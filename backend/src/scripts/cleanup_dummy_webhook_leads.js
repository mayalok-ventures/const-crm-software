/**
 * Safe, Targeted Cleanup Utility for Dummy/Test Webhook Leads
 * 
 * Usage:
 *   node cleanup_dummy_webhook_leads.js             (Dry Run: previews records)
 *   node cleanup_dummy_webhook_leads.js --confirm   (Execution: deletes ONLY explicit matched IDs)
 */

const mongoose = require('mongoose');
const dotenv = require('dotenv');
dotenv.config();

const Lead = require('../models/Lead');
const AuditLog = require('../models/AuditLog');

const isConfirm = process.argv.includes('--confirm');

async function runCleanup() {
  console.log('═══════════════════════════════════════════════════════════════════');
  console.log(`🧹 TEST / DUMMY WEBHOOK LEADS TARGETED CLEANUP (${isConfirm ? 'CONFIRM MODE' : 'DRY RUN MODE'})`);
  console.log('═══════════════════════════════════════════════════════════════════\n');

  await mongoose.connect(process.env.MONGODB_URI);
  console.log('✅ Connected to MongoDB Database');

  // Explicit, multi-attribute matching criteria for automated test / dummy webhook records
  const query = {
    $or: [
      // Test emails generated during automated suites
      { email: /@(crmtest\.com|example\.com|test\.local)$/i },
      // Explicit test payload markers in metadata
      { 'metadata.is_test_event': true },
      { 'metadata.test_run': true },
      { 'customData.isTest': true },
      // Test webhook identifiers
      { 'leadSource.formId': /^test_form_/i },
      { 'leadSource.campaignId': /^test_campaign_/i },
      { 'leadSource.externalLeadId': /^test_lead_/i },
      // Dummy inquiry titles generated by load tests
      { name: /^Test Prospect Webhook/i },
      { name: /^Higher Ed Institute Lead_/i },
      { name: /^NextGen EdTech Lead_/i },
      { name: /^Global Horizons Overseas Lead_/i },
      { name: /^Apex IIT-JEE & Medical Academy Lead_/i },
      { name: /^Oakridge World School Lead_/i },
      { name: /^Direct Admission Counsellors Lead_/i },
    ]
  };

  // Find all matched records
  const matchedLeads = await Lead.find(query).select('_id name phone email source primarySource leadSource createdAt companyId');
  const matchedIds = matchedLeads.map(l => l._id);

  console.log(`\n🔍 Matched Dummy/Test Records Found: ${matchedLeads.length}`);

  if (matchedLeads.length === 0) {
    console.log('✨ No dummy/test webhook leads found in database. Database is already clean.');
    await mongoose.disconnect();
    return;
  }

  console.log('\n📋 Sample Matched Records (First 10):');
  matchedLeads.slice(0, 10).forEach((lead, i) => {
    console.log(`  [${i + 1}] ID: ${lead._id} | Name: "${lead.name}" | Email: "${lead.email || 'N/A'}" | Phone: "${lead.phone}" | Source: "${lead.source}"`);
  });

  if (!isConfirm) {
    console.log('\n⚠️  DRY RUN COMPLETED. No data was modified or deleted.');
    console.log('👉 To permanently delete ONLY these explicitly matched records, re-run with:');
    console.log('   node src/scripts/cleanup_dummy_webhook_leads.js --confirm\n');
    await mongoose.disconnect();
    return;
  }

  // Confirm execution: delete ONLY the explicit matched IDs
  console.log(`\n🗑️  Executing targeted deletion of ${matchedIds.length} explicitly matched record IDs...`);
  const deleteResult = await Lead.deleteMany({ _id: { $in: matchedIds } });

  console.log(`✅ Successfully deleted ${deleteResult.deletedCount} dummy test lead records.`);

  // Record Audit Trail
  try {
    if (AuditLog) {
      await AuditLog.create({
        action: 'TEST_DATA_CLEANUP',
        resourceType: 'Lead',
        metadata: {
          matchedCount: matchedIds.length,
          deletedCount: deleteResult.deletedCount,
          deletedIds: matchedIds.map(id => id.toString()),
        },
        timestamp: new Date(),
      });
      console.log('📝 Audit log recorded for data cleanup.');
    }
  } catch (e) {
    console.log('ℹ️  Audit log creation note:', e.message);
  }

  // Final count verification
  const remainingCount = await Lead.countDocuments();
  console.log(`📊 Remaining Total Leads in Database: ${remainingCount}`);

  await mongoose.disconnect();
  console.log('\n═══════════════════════════════════════════════════════════════════');
}

runCleanup().catch(err => {
  console.error('❌ Cleanup failed:', err);
  process.exit(1);
});
