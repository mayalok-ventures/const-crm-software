const seedPlans = async () => {
  try {
    for (const planData of SEED_PLANS) {
      const monthlyAmount = planData.pricing?.monthly?.amount || Math.round((planData.priceInPaise || 0) / 100);
      const yearlyAmount = planData.pricing?.yearly?.amount || monthlyAmount * 10;

      const completePlan = {
        ...planData,
        price: monthlyAmount,
        monthlyPrice: monthlyAmount,
        yearlyPrice: yearlyAmount,
        pricing: {
          monthly: {
            enabled: planData.pricing?.monthly?.enabled !== false,
            amount: monthlyAmount,
            priceInPaise: monthlyAmount * 100,
          },
          yearly: {
            enabled: planData.pricing?.yearly?.enabled !== false,
            amount: yearlyAmount,
            priceInPaise: yearlyAmount * 100,
          },
          currency: 'INR',
        },
      };

      await Plan.findOneAndUpdate(
        { code: planData.code },
        { $set: completePlan },
        { upsert: true, new: true }
      );
    }
    console.log(`[Billing Engine] Seeded ${SEED_PLANS.length} dynamic versioned Subscription Plans. ✅`);
  } catch (err) {
    console.error('[Billing Engine] Error seeding dynamic plans:', err.message);
  }
};

module.exports = { seedPlans, SEED_PLANS };
