const seedPlans = async () => {
  try {
    for (const planData of SEED_PLANS) {
      await Plan.findOneAndUpdate(
        { code: planData.code },
        { $set: planData },
        { upsert: true, new: true }
      );
    }
    console.log(`[Billing Engine] Seeded ${SEED_PLANS.length} standardized Subscription Plans. ✅`);
  } catch (err) {
    console.error('[Billing Engine] Error seeding plans:', err.message);
  }
};

